---@module 'busted'

local helpers = require('tests.helpers')

describe('layout', function()
  local ui

  before_each(function()
    helpers.reset_editor()
    ui = require('codecompanion-ui')
  end)

  after_each(function()
    helpers.reset_editor()
  end)

  describe('attach', function()
    it('opens an input window below the chat window', function()
      helpers.toggle()
      helpers.assert_open()
      assert.is_true(ui.is_visible())

      local session = helpers.session()
      local chat_pos = vim.api.nvim_win_get_position(session.chat_winid)
      local input_pos = vim.api.nvim_win_get_position(session.input_winid)
      assert.equals(chat_pos[2], input_pos[2], 'input should share the chat column')
      assert.is_true(input_pos[1] > chat_pos[1], 'input should be below the chat')
    end)
  end)

  describe('toggle', function()
    it('hides and shows both windows across repeated toggles', function()
      helpers.toggle()
      for _ = 1, 3 do
        helpers.toggle()
        helpers.assert_closed()
        assert.is_false(ui.is_visible())
        helpers.toggle()
        helpers.assert_open()
        assert.is_true(ui.is_visible())
      end
    end)

    it('does not leak input buffers across hide/show cycles', function()
      helpers.toggle()
      for _ = 1, 3 do
        helpers.toggle()
        helpers.toggle()
      end
      assert.equals(1, helpers.count_bufs('codecompanion_input'))
    end)

    it('preserves the input draft across hide/show', function()
      helpers.toggle()
      vim.api.nvim_buf_set_lines(helpers.session().input_bufnr, 0, -1, false, { 'draft', 'line two' })
      helpers.toggle()
      helpers.toggle()
      local lines = vim.api.nvim_buf_get_lines(helpers.session().input_bufnr, 0, -1, false)
      assert.same({ 'draft', 'line two' }, lines)
    end)
  end)

  describe(':q on the chat window', function()
    it('closes the input window too', function()
      helpers.toggle()
      helpers.quit_win(helpers.session().chat_winid)
      helpers.assert_closed()
    end)

    it('clears the session window state', function()
      helpers.toggle()
      local session = helpers.session()
      helpers.quit_win(session.chat_winid)
      assert.is_nil(session.input_winid)
      assert.is_nil(session.input_bufnr)
      assert.is_false(ui.is_visible())
    end)

    it('reopens with both windows on the next toggle', function()
      helpers.toggle()
      helpers.quit_win(helpers.session().chat_winid)
      helpers.toggle()
      helpers.assert_open()
    end)
  end)

  describe(':q on the input window', function()
    it('closes the chat window too', function()
      helpers.toggle()
      helpers.quit_win(helpers.session().input_winid)
      helpers.assert_closed()
    end)

    it('hides the chat through codecompanion', function()
      helpers.toggle()
      local session = helpers.session()
      local chat = require('codecompanion').buf_get_chat(session.chat_bufnr)
      helpers.quit_win(session.input_winid)
      assert.is_false(chat.ui:is_visible())
      assert.is_nil(session.input_winid)
    end)

    it('reopens with both windows and the draft restored', function()
      helpers.toggle()
      local session = helpers.session()
      vim.api.nvim_buf_set_lines(session.input_bufnr, 0, -1, false, { 'hello draft' })
      helpers.quit_win(session.input_winid)
      helpers.toggle()
      helpers.assert_open()
      local lines = vim.api.nvim_buf_get_lines(helpers.session().input_bufnr, 0, -1, false)
      assert.same({ 'hello draft' }, lines)
    end)
  end)

  describe(':only from another window', function()
    it('closes both windows and reopens cleanly', function()
      helpers.toggle()
      vim.api.nvim_set_current_win(helpers.other_win(helpers.session()))
      vim.cmd('only')
      helpers.flush()
      helpers.assert_closed()
      helpers.toggle()
      helpers.assert_open()
    end)
  end)

  describe('attach with stale session state', function()
    it('recreates the input window when the stored window id is invalid', function()
      helpers.toggle()
      local session = helpers.session()
      -- Simulate the input window vanishing without any of our autocmds firing.
      vim.cmd('noautocmd ' .. vim.api.nvim_win_get_number(session.input_winid) .. 'wincmd c')
      assert.is_false(vim.api.nvim_win_is_valid(session.input_winid))
      helpers.toggle() -- hide (chat still visible)
      helpers.toggle() -- show
      helpers.assert_open()
      assert.is_true(vim.api.nvim_win_is_valid(helpers.session().input_winid))
    end)
  end)
end)
